#: Every run happens under a throwaway home. A mutant is broken code by definition, and
#: some of the breaks are exactly "writes where it should not": one of them once left a
#: state file in the real ~/.claude while the suite was busy catching it.
SANDBOX_HOME = None


def run(cwd):
    env = dict(os.environ, HOME=SANDBOX_HOME) if SANDBOX_HOME else None
    p = subprocess.run([sys.executable, '-m', 'unittest', 'discover', '-s', 'tests', '-t', 'tests'],
                       cwd=cwd, capture_output=True, text=True, stdin=subprocess.DEVNULL, env=env)
    return p.returncode == 0, (p.stderr or '').strip().splitlines()[-1:]


def main():
    global SANDBOX_HOME
    SANDBOX_HOME = tempfile.mkdtemp(prefix='horme-mut-home-')
    try:
        return _main()
    finally:
        shutil.rmtree(SANDBOX_HOME, ignore_errors=True)


def _main():
    ok, _ = run(ROOT)
    if not ok:
        print('BASELINE IS RED — fix that before mutation testing'); return 2
    print('baseline: green\n')
    caught = survived = 0
    for fname, old, new, why in MUTANTS:
        tmp = tempfile.mkdtemp(prefix='horme-mut-')
        dst = os.path.join(tmp, 'horme')
        shutil.copytree(ROOT, dst, ignore=shutil.ignore_patterns('.git', 'snapshots', '__pycache__'))
        target = os.path.join(dst, 'src', 'horme', fname)
        src = open(target, encoding='utf-8').read()
        if old not in src:
            print('  ?? MUTANT NOT APPLICABLE (%s): anchor missing' % fname); survived += 1
            shutil.rmtree(tmp, ignore_errors=True); continue
        open(target, 'w', encoding='utf-8').write(src.replace(old, new, 1))
        green, tail = run(dst)
        if green:
            print('  SURVIVED  %-14s %s' % (fname, why)); survived += 1
        else:
            print('  caught    %-14s %s' % (fname, why)); caught += 1
        shutil.rmtree(tmp, ignore_errors=True)
    print('\nmutants caught %d/%d' % (caught, caught + survived))
    return 0 if survived == 0 else 1


if __name__ == '__main__':
    sys.exit(main())
